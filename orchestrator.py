# 7. Orchestrator — Main Decision Engine
# ---------------------------------------------------------------------------

class BayesianOrchestrator:
    """
    The CTO's decision engine. Evaluates every Alpha Stack signal
    through Bayesian inference and either authorizes or rejects it.

    Process per signal:
        1. Fetch Prior P(A) from TimescaleDB (via Redis cache).
        2. Fetch Macro Context from Macro-MCP (via Redis cache).
        3. Compute Likelihood P(B|A) with IOF, Macro, Hurst adjustments.
        4. Compute Posterior P(A|B) via odds-form Bayes.
        5. Decision: AUTHORIZE if posterior > 69.5%, else REJECT.
        6. Route authorized signals to the correct broker connector.
    """

    def __init__(self, redis_url: str = REDIS_URL) -> None:
        self._redis_url = redis_url
        self._pool: aioredis.Redis | None = None

        # Counters
        self._evaluated: int = 0
        self._authorized: int = 0
        self._rejected: int = 0

    async def connect(self) -> None:
        self._pool = aioredis.from_url(
            self._redis_url,
            decode_responses=False,
            max_connections=10,
            socket_connect_timeout=5.0,
            socket_keepalive=True,
        )
        await self._pool.ping()
        await log.ainfo("orchestrator_connected")

    async def disconnect(self) -> None:
        if self._pool:
            await self._pool.aclose()
        await log.ainfo(
            "orchestrator_disconnected",
            evaluated=self._evaluated,
            authorized=self._authorized,
            rejected=self._rejected,
            auth_rate=round(self._authorized / max(self._evaluated, 1), 4),
        )

    async def evaluate_signal(self, signal: SignalInput) -> OrchestratorOutput:
        """
        Full Bayesian evaluation pipeline for a single signal.

        Returns an OrchestratorOutput with AUTHORIZE or REJECT decision
        and complete mathematical reasoning trail.
        """
        t0 = time.perf_counter()

        # --- Step 1: Fetch Prior P(A) ---
        prior = await fetch_prior(
            asset_symbol=signal.asset_symbol,
            desk_id=signal.desk_id,
            redis_pool=self._pool,
        )

        # --- Step 2: Fetch Macro Context ---
        macro = await fetch_macro_context(self._pool)

        # --- Step 3: Compute Likelihood P(B|A) ---
        likelihood, likelihood_reasoning = compute_likelihood(signal, macro)

        # --- Step 4: Compute Posterior P(A|B) ---
        posterior = compute_posterior(prior, likelihood)

        # --- Step 5: Decision ---
        if posterior > POSTERIOR_FLOOR:
            decision = Decision.AUTHORIZE
            routing = resolve_routing_target(signal.asset_class)
            self._authorized += 1
        else:
            decision = Decision.REJECT
            routing = None
            self._rejected += 1

        self._evaluated += 1
        elapsed_us = (time.perf_counter() - t0) * 1_000_000

        # --- Build reasoning string ---
        reasoning = (
            f"P(A)={prior:.4f} [30d win rate] × "
            f"L={likelihood:.4f} [{likelihood_reasoning}] → "
            f"P(A|B)={posterior:.6f} "
            f"{'>' if posterior > POSTERIOR_FLOOR else '≤'} "
            f"{POSTERIOR_FLOOR} threshold"
        )

        output = OrchestratorOutput(
            signal_id=signal.signal_id,
            posterior_probability=posterior,
            decision=decision.value,
            routing_target=routing.value if routing else None,
            reasoning_math=reasoning,
        )

        # --- Step 6: Route authorized signals ---
        if decision == Decision.AUTHORIZE and self._pool is not None:
            await self._route_signal(signal, output)

        # --- Structured log ---
        await log.ainfo(
            "signal_evaluated",
            signal_id=signal.signal_id,
            symbol=signal.asset_symbol,
            model=signal.model_source,
            prior=round(prior, 4),
            likelihood=round(likelihood, 4),
            posterior=round(posterior, 6),
            decision=decision.value,
            routing=routing.value if routing else "DROPPED",
            latency_us=round(elapsed_us, 1),
        )

        return output

    async def _route_signal(
        self,
        signal: SignalInput,
        output: OrchestratorOutput,
    ) -> None:
        """
        Route an authorized signal to the appropriate broker connector.

        Pushes to the `oniquant:active_executions` Redis Stream with
        routing metadata so the execution layer knows which broker
        module to invoke.
        """
        execution_payload: dict[str, Any] = {
            "signal_id": signal.signal_id,
            "asset_symbol": signal.asset_symbol,
            "asset_class": signal.asset_class,
            "direction": signal.direction,
            "target_price": signal.target_price,
            "confidence": signal.confidence,
            "desk_id": signal.desk_id,
            "model_source": signal.model_source,
            "posterior_probability": output.posterior_probability,
            "routing_target": output.routing_target,
            "decision": output.decision,
            "reasoning_math": output.reasoning_math,
            "authorized_at": time.time(),
            "indicator_metadata": signal.indicator_metadata,
        }

        await self._pool.xadd(
            EXEC_STREAM,
            {
                "payload": orjson.dumps(execution_payload),
                "source": b"bayesian_orchestrator",
            },
            maxlen=EXEC_STREAM_MAXLEN,
            approximate=True,
        )

    # ------------------------------------------------------------------
    # Batch evaluation (for backtest / replay)
    # ------------------------------------------------------------------

    async def evaluate_batch(
        self,
        signals: list[SignalInput],
    ) -> list[OrchestratorOutput]:
        """
        Evaluate a batch of signals concurrently.

        Uses asyncio.gather for parallel Prior/Macro fetches across signals.
        """
        tasks = [self.evaluate_signal(s) for s in signals]
        return await asyncio.gather(*tasks)

    # ------------------------------------------------------------------
    # Statistics
    # ------------------------------------------------------------------

    @property
    def stats(self) -> dict[str, Any]:
        total = max(self._evaluated, 1)
        return {
            "evaluated": self._evaluated,
            "authorized": self._authorized,
            "rejected": self._rejected,
            "auth_rate": round(self._authorized / total, 4),
            "reject_rate": round(self._rejected / total, 4),
        }


# ---------------------------------------------------------------------------
# 8. Stream Consumer — Continuous Signal Processing Loop
# ---------------------------------------------------------------------------

async def run_orchestrator_consumer(
    redis_url: str = REDIS_URL,
    input_stream: str = "oniquant:raw_signals",
    consumer_group: str = "orchestrator_cg",
    consumer_name: str = "orchestrator_worker_0",
) -> None:
    """
    Consume signals from Redis Stream and run Bayesian evaluation.

    Uses XREADGROUP consumer group pattern for:
        - At-least-once delivery guarantee
        - Horizontal scaling (multiple consumer workers)
        - Automatic rebalancing on worker failure

    Flow:
        XREADGROUP oniquant:raw_signals → parse signal → evaluate → XACK
    """
    orchestrator = BayesianOrchestrator(redis_url=redis_url)
    await orchestrator.connect()

    pool = await orchestrator._pool

    # Ensure consumer group exists (idempotent)
    try:
        await pool.xgroup_create(input_stream, consumer_group, id="0", mkstream=True)
    except aioredis.ResponseError as e:
        if "BUSYGROUP" not in str(e):
            raise

    await log.ainfo(
        "orchestrator_consumer_started",
        stream=input_stream,
        group=consumer_group,
        consumer=consumer_name,
    )

    while True:
        try:
            # Block for up to 1 second waiting for new messages
            messages = await pool.xreadgroup(
                groupname=consumer_group,
                consumername=consumer_name,
                streams={input_stream: ">"},
                count=10,
                block=1000,
            )

            if not messages:
                continue

            for stream_name, entries in messages:
                for msg_id, msg_data in entries:
                    try:
                        raw_payload = msg_data.get(b"payload", b"{}")
                        payload = orjson.loads(raw_payload)

                        # Construct SignalInput from raw payload
                        signal = SignalInput(
                            signal_id=payload.get("signal_id", str(uuid.uuid4())),
                            asset_symbol=payload.get("asset_symbol", "UNKNOWN"),
                            asset_class=payload.get("asset_class", "equity"),
                            desk_id=payload.get("desk_id", "unknown"),
                            direction=payload.get("signal_direction", 1),
                            target_price=payload.get("target_price", 0.0),
                            confidence=payload.get("confidence", 0.5),
                            model_source=payload.get("model_source", "unknown"),
                            iof_strength=payload.get("iof_strength", 0.5),
                            hurst_exponent=payload.get("hurst_exponent", 0.5),
                            macro_context=payload.get("macro_context", {}),
                            indicator_metadata=payload.get("indicator_metadata", {}),
                        )

                        # Evaluate through Bayesian engine
                        result = await orchestrator.evaluate_signal(signal)

                        # ACK the message — successfully processed
                        await pool.xack(input_stream, consumer_group, msg_id)

                    except Exception as e:
                        await log.aerror(
                            "signal_processing_error",
                            msg_id=msg_id,
                            error=str(e),
                            error_type=type(e).__name__,
                        )
                        # Don't ACK — message will be re-delivered to another consumer

        except aioredis.ConnectionError as e:
            await log.aerror("orchestrator_redis_lost", error=str(e))
            await asyncio.sleep(2.0)
        except Exception as e:
            await log.aerror("orchestrator_loop_error", error=str(e))
            await asyncio.sleep(0.5)


