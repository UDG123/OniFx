"""
OniQuant v6.0 — Phase 5.5: Bayesian Decision Engine (Orchestrator)
====================================================================
Final arbiter for all signals generated by the Alpha Stack.
Authorizes or rejects signals based on Bayesian Posterior Probability
with a hard floor of 69.5%.

Bayes' Theorem:
                    P(B|A) × P(A)
    P(A|B)  =  ─────────────────────
                       P(B)

Where:
    P(A)    = Prior: 30-day historical win rate from TimescaleDB
    P(B|A)  = Likelihood: adjusted by IOF strength, macro alignment, Hurst exponent
    P(B)    = Evidence: marginal probability (normalizing constant)
    P(A|B)  = Posterior: final decision probability

Decision Rule:
    If P(A|B) > 0.695 → AUTHORIZE (route to broker)
    If P(A|B) ≤ 0.695 → REJECT (drop silently)

Routing:
    TradFi (equities, forex, metals) → broker_tradfi.py (IBKR_TWS)
    Crypto (perpetuals, spot)        → broker_crypto.py (BYBIT_V5)

Deploy: Railway.app — imported by the signal processing pipeline.
"""

